import AppKit
import Carbon

struct LocalStore {
    let directory: URL

    static let standard = LocalStore(directory: URL.applicationSupportDirectory
        .appendingPathComponent("HelpfulUtilities", isDirectory: true))

    func read<T: Decodable>(_ name: String, as type: T.Type) -> T? {
        let url = directory.appendingPathComponent(name)
        guard let size = (try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize,
              size <= 24 * 1024 * 1024, let data = try? Data(contentsOf: url) else { return nil }
        return try? JSONDecoder().decode(type, from: data)
    }

    func write<T: Encodable>(_ value: T, to name: String) throws {
        let manager = FileManager.default
        try manager.createDirectory(at: directory, withIntermediateDirectories: true,
                                    attributes: [.posixPermissions: 0o700])
        let url = directory.appendingPathComponent(name)
        try JSONEncoder().encode(value).write(to: url, options: .atomic)
        try manager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}

struct Clip: Codable {
    let text: String
    let date: Date

    var label: String {
        let sample = String(text.prefix(180))
        return sample.components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }.joined(separator: " ")
    }
}

final class ClipboardHistory {
    static let limit = 80
    static let maxBytes = 32_768
    private static let totalBytes = 512 * 1024
    private static let file = "clipboard.json"
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "com.apple.is-remote-clipboard", "com.apple.pasteboard.promised-file-url",
        "public.file-url", "NSFilenamesPboardType"
    ]

    private let board: NSPasteboard
    private let store: LocalStore
    private var lastCount: Int
    private var timer: Timer?
    private(set) var clips: [Clip]
    var onChange: (() -> Void)?
    var onError: ((Error) -> Void)?

    init(board: NSPasteboard = .general, store: LocalStore) {
        self.board = board
        self.store = store
        lastCount = board.changeCount
        clips = Array((store.read(Self.file, as: [Clip].self) ?? [])
            .filter { $0.text.utf8.count <= Self.maxBytes }.prefix(Self.limit))
    }

    func setRecording(_ enabled: Bool) {
        timer?.invalidate()
        timer = nil
        lastCount = board.changeCount
        guard enabled else { return }
        let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func poll() {
        let count = board.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard !IsSecureEventInputEnabled(),
              let types = board.types,
              types.contains(.string),
              !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }),
              let data = board.data(forType: .string), data.count <= Self.maxBytes,
              let text = board.string(forType: .string), text.utf8.count <= Self.maxBytes,
              count == board.changeCount,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        clips.removeAll { $0.text == text }
        clips.insert(Clip(text: text, date: Date()), at: 0)
        var remainingBytes = Self.totalBytes
        clips = Array(clips.prefix(Self.limit).prefix {
            remainingBytes -= $0.text.utf8.count
            return remainingBytes >= 0
        })
        save()
    }

    func copy(_ clip: Clip) {
        board.clearContents()
        board.setString(clip.text, forType: .string)
        lastCount = board.changeCount
    }

    func remove(_ clip: Clip) {
        clips.removeAll { $0.text == clip.text }
        save()
    }

    func clear() {
        clips.removeAll()
        save()
    }

    private func save() {
        do { try store.write(clips, to: Self.file) }
        catch { onError?(error) }
        onChange?()
    }
}

final class NoteStore {
    static let count = 7
    static let maxBytes = 512 * 1024
    private static let file = "notes.json"
    private let store: LocalStore
    private(set) var notes: [String]

    init(store: LocalStore) {
        self.store = store
        if let saved = store.read(Self.file, as: [String].self), saved.count == Self.count {
            notes = saved
        } else {
            notes = Array(repeating: "", count: Self.count)
        }
    }

    func save(_ text: String, at index: Int) throws {
        guard notes[index] != text else { return }
        var updated = notes
        updated[index] = text
        try store.write(updated, to: Self.file)
        notes = updated
    }
}
